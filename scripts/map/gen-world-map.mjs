// Build-time generator: dotted world map (Natural Earth 110m land) as compact SVG paths.
// Output: origin/world-map.js (no runtime dependencies).
import { readFileSync, writeFileSync } from "node:fs";
import { feature } from "topojson-client";
import { geoNaturalEarth1, geoContains } from "d3-geo";

const OUT = process.argv[2];
const W = 720, STEP = 6, CENTER_LON = 118;

const topo = JSON.parse(readFileSync("node_modules/world-atlas/land-110m.json", "utf8"));
const land = feature(topo, topo.objects.land);

const proj = geoNaturalEarth1().rotate([-CENTER_LON, 0]).fitWidth(W, { type: "Sphere" });
const yTop = proj([CENTER_LON, 64])[1];
const yBot = proj([CENTER_LON, -42])[1];
const [tx, ty] = proj.translate();
proj.translate([tx, ty - yTop]);
const H = Math.round(yBot - yTop);

const cities = {
  SIN: [103.82, 1.35], SJC: [-121.89, 37.34], LAX: [-118.24, 34.05], FRA: [8.68, 50.11],
  LHR: [-0.45, 51.47], NRT: [139.69, 35.69], SYD: [151.21, -33.87], BOM: [72.88, 19.08],
  BKK: [100.5, 13.76], HKG: [114.17, 22.32], DXB: [55.27, 25.2], JNB: [28.05, -26.2],
  CGK: [106.85, -6.21], SEA: [-122.33, 47.61],
};
const px = Object.fromEntries(
  Object.entries(cities).map(([k, ll]) => [k, proj(ll).map((v) => Math.round(v * 10) / 10)])
);
const [sx, sy] = px.SIN;

const buckets = { near: [], mid: [], far: [] };
let total = 0;
for (let y = Math.round(STEP / 2); y < H; y += STEP) {
  for (let x = Math.round(STEP / 2); x < W; x += STEP) {
    const ll = proj.invert([x, y]);
    if (!ll || !Number.isFinite(ll[0])) continue;
    const back = proj(ll);
    if (!back || Math.hypot(back[0] - x, back[1] - y) > 0.5) continue; // outside the map outline
    if (!geoContains(land, ll)) continue;
    const d = Math.hypot(x - sx, y - sy);
    (d < 100 ? buckets.near : d < 230 ? buckets.mid : buckets.far).push(`M${x} ${y}h0`);
    total++;
  }
}

const src = `// GENERATED by scripts/gen-world-map (Natural Earth 110m land via world-atlas, public domain).
// Natural Earth projection centred on ${CENTER_LON}°E, ${W}x${H}, ${STEP}px dot grid, ${total} land dots.
module.exports = {
  width: ${W},
  height: ${H},
  dots: {
    near: "${buckets.near.join("")}",
    mid: "${buckets.mid.join("")}",
    far: "${buckets.far.join("")}",
  },
  cities: ${JSON.stringify(px)},
};
`;
writeFileSync(OUT, src);
console.log(`wrote ${OUT}: ${W}x${H}, ${total} dots (near ${buckets.near.length}, mid ${buckets.mid.length}, far ${buckets.far.length}), ${src.length} bytes`);
console.log(px);
